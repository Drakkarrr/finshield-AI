export default function Sidebar() {
  const pathname = usePathname();
  const { user } = useAuth();
  const credits = calcCredits(user?.total_credits ?? 0, user?.used_credits ?? 0);
  const sections = NAV_SECTIONS
    .map((s) => ({ ...s, items: s.items.filter((i) => !i.requires || canCall(user?.role, i.requires)) }))
    .filter((s) => s.items.length > 0);
  const daysLeft = user?.is_trial && user.trial_expires_at ? trialDaysLeft(user.trial_expires_at) : null;

  return (
    <aside className="fixed left-0 top-0 bottom-0 w-sidebar bg-navy flex flex-col z-sidebar">
      <div className="px-6 py-5 border-b border-white/10">
        <Link href="/dashboard" className="flex items-center gap-2.5">
          <span className="w-8 h-8 bg-accent/15 rounded-lg flex items-center justify-center">
            <svg className="w-5 h-5 text-accent" aria-hidden="true" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M9 12.75L11.25 15 15 9.75m-3-7.036A11.959 11.959 0 013.598 6 11.99 11.99 0 003 9.749c0 5.592 3.824 10.29 9 11.623 5.176-1.332 9-6.03 9-11.622 0-1.31-.21-2.571-.598-3.751h-.152c-3.196 0-6.1-1.248-8.25-3.285z" />
            </svg>
          </span>
          <span className="text-white font-bold text-sm">FinShield</span>
        </Link>
      </div>

      <nav aria-label="Main" className="flex-1 overflow-y-auto py-4 px-3">
        {sections.map((section) => (
          <div key={section.label} className="mb-5">
            <h2 className="px-3 mb-1.5 text-2xs font-semibold text-white/50 uppercase tracking-wider">{section.label}</h2>
            <ul>
              {section.items.map((item) => {
                const isActive = pathname === item.href || pathname?.startsWith(item.href + '/');
                return (
                  <li key={item.href}>
                    <Link
                      href={item.href}
                      aria-current={isActive ? 'page' : undefined}
                      className={`flex items-center gap-3 px-3 py-2 rounded-lg text-sm transition-colors mb-0.5 ${
                        isActive ? 'bg-accent/15 text-accent font-medium' : 'text-white/70 hover:bg-white/5 hover:text-white'
                      }`}
                    >
                      <span className={isActive ? 'text-accent' : 'text-white/50'}>{ICONS[item.icon]}</span>
                      {item.label}
                    </Link>
                  </li>
                );
              })}
            </ul>
          </div>
        ))}
      </nav>

      <div className="px-4 py-4 border-t border-white/10">
        {daysLeft !== null && (
          <p className={`mb-2 rounded-lg px-3 py-2 text-center text-2xs font-semibold border ${
            daysLeft === 0 ? 'bg-danger/10 border-danger/30 text-white' : 'bg-accent/10 border-accent/20 text-accent'
          }`}>
            {daysLeft === 0 ? 'Trial expired' : `Free trial · ${daysLeft} day${daysLeft === 1 ? '' : 's'} left`}
          </p>
        )}
        <div className="bg-white/5 rounded-xl px-4 py-3">
          <div className="flex items-center justify-between mb-1">
            <span className="text-xs text-white/60">Credits</span>
            <span className="text-xs text-accent font-semibold">{formatNumber(credits.remaining)}</span>
          </div>
          <Meter value={credits.used} max={credits.total || 1} label="Credits used" valueText={`${credits.pctUsed}% used`} />
          <p className="text-2xs text-white/50 mt-1">{formatNumber(credits.used)} of {formatNumber(credits.total)} used ({credits.pctUsed}%)</p>
        </div>
        {user && (
          <p className="text-2xs text-white/50 text-center mt-2">
            Role: <span className="text-white/80 font-medium capitalize">{user.role}</span>
          </p>
        )}
        <Link href="/settings?tab=billing" className="mt-2 block text-center text-2xs text-white/60 hover:text-accent transition-colors">
          {user?.is_trial ? 'Upgrade plan →' : 'Billing →'}
        </Link>
      </div>
    </aside>
  );
}
